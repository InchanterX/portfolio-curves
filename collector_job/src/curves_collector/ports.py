from datetime import date
from typing import Protocol

from curves_collector.domain import Curve


class Source(Protocol):
    def fetch(self, start: date, end: date) -> list[Curve]: ...


class Repository(Protocol):
    def latest_date(self) -> date | None: ...
    def save(self, batch_id: int, curves: list[Curve]) -> int: ...
    def start_batch(self) -> int: ...
    def finish_batch(self, batch_id: int, error: str | None = None) -> None: ...

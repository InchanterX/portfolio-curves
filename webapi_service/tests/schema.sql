CREATE SCHEMA auth;
CREATE SCHEMA ref;
CREATE SCHEMA market;
CREATE SCHEMA app;
CREATE SCHEMA calc;
CREATE SCHEMA audit;

CREATE TABLE auth.user_account (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email varchar(320) NOT NULL CHECK (email=trim(email) AND length(email)>0),
 display_name varchar(256) NOT NULL CHECK (length(trim(display_name))>0),
 password_hash text NOT NULL CHECK (length(trim(password_hash))>0),
 role varchar(16) NOT NULL DEFAULT 'viewer' CHECK (role IN ('viewer','editor')),
 status varchar(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','active','disabled')),
 email_confirmed_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (status<>'active' OR email_confirmed_at IS NOT NULL),
 CHECK (updated_at>=created_at AND (email_confirmed_at IS NULL OR email_confirmed_at>=created_at))
);
CREATE UNIQUE INDEX uq_user_account_email ON auth.user_account (lower(email));
CREATE TABLE auth.user_session (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES auth.user_account,
 token_hash varchar(64) NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
 created_at timestamptz NOT NULL DEFAULT now(), expires_at timestamptz NOT NULL, revoked_at timestamptz,
 CHECK (expires_at>created_at AND (revoked_at IS NULL OR revoked_at>=created_at))
);
CREATE INDEX ix_user_session_user ON auth.user_session(user_id);
CREATE TABLE auth.action_token (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES auth.user_account,
 purpose varchar(32) NOT NULL CHECK (purpose IN ('verify_email','reset_password')),
 token_hash varchar(64) NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
 created_at timestamptz NOT NULL DEFAULT now(), expires_at timestamptz NOT NULL, used_at timestamptz,
 CHECK (expires_at>created_at AND (used_at IS NULL OR used_at>=created_at))
);
CREATE INDEX ix_action_token_user ON auth.action_token(user_id);
CREATE TABLE ref.bucket_set (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(64) NOT NULL, version_no integer NOT NULL CHECK (version_no>0), name varchar(256) NOT NULL,
 UNIQUE(code,version_no)
);
CREATE TABLE ref.time_bucket (
 bucket_set_id bigint NOT NULL REFERENCES ref.bucket_set,
 bucket_no smallint NOT NULL CHECK(bucket_no>0), label varchar(16) NOT NULL,
 lower_years numeric(12,8) NOT NULL, upper_years numeric(12,8), tenor_years numeric(12,8) NOT NULL,
 PRIMARY KEY(bucket_set_id,bucket_no), UNIQUE(bucket_set_id,label),
 CHECK(lower_years>=0 AND (upper_years IS NULL OR upper_years>lower_years)),
 CHECK(tenor_years>0 AND tenor_years>=lower_years AND (upper_years IS NULL OR tenor_years<=upper_years))
);
CREATE TABLE market.ingestion_batch (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source varchar(32) NOT NULL, status varchar(16) NOT NULL DEFAULT 'running'
 CHECK(status IN ('running','succeeded','failed')),
 started_at timestamptz NOT NULL DEFAULT now(), finished_at timestamptz, error_message text,
 CHECK(finished_at IS NULL OR finished_at>=started_at)
);
CREATE TABLE market.curve (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ingestion_batch_id bigint NOT NULL REFERENCES market.ingestion_batch,
 source varchar(32) NOT NULL, curve_code varchar(32) NOT NULL,
 currency_code varchar(3) NOT NULL DEFAULT 'RUB' CHECK(currency_code ~ '^[A-Z]{3}$'),
 curve_date date NOT NULL, revision integer NOT NULL DEFAULT 1 CHECK(revision>0),
 status varchar(16) NOT NULL DEFAULT 'loading' CHECK(status IN ('loading','accepted','rejected')),
 rate_convention varchar(64), payload jsonb NOT NULL,
 payload_sha256 varchar(64) NOT NULL CHECK(payload_sha256 ~ '^[0-9a-f]{64}$'),
 loaded_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(source,curve_code,currency_code,curve_date,revision),
 UNIQUE(source,curve_code,currency_code,curve_date,payload_sha256)
);
CREATE INDEX ix_curve_batch ON market.curve(ingestion_batch_id);
CREATE TABLE market.curve_point (
 curve_id bigint NOT NULL REFERENCES market.curve,
 point_no smallint NOT NULL CHECK(point_no>0), tenor_years numeric(12,8) NOT NULL CHECK(tenor_years>0),
 rate_pct numeric(18,10) NOT NULL, PRIMARY KEY(curve_id,point_no), UNIQUE(curve_id,tenor_years)
);
CREATE TABLE app.methodology_version (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(64) NOT NULL, version_no integer NOT NULL CHECK(version_no>0), name varchar(256) NOT NULL,
 status varchar(16) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','ready','retired')),
 bucket_set_id bigint NOT NULL REFERENCES ref.bucket_set,
 x numeric(12,8) CHECK(x>0), parallel_shift_pp numeric(18,10), short_shift_pp numeric(18,10), long_shift_pp numeric(18,10),
 floor_mode varchar(16) CHECK(floor_mode IN ('none','constant','by_bucket')), floor_params jsonb,
 interpolation_method varchar(64), extrapolation_method varchar(64), nearest_method varchar(64),
 rate_convention varchar(64), source_document varchar(512), created_by varchar(128) NOT NULL,
 created_by_user_id bigint REFERENCES auth.user_account, created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(code,version_no), UNIQUE(id,bucket_set_id),
 CHECK(parallel_shift_pp>=0 AND short_shift_pp>=0 AND long_shift_pp>=0),
 CONSTRAINT ck_methodology_ready CHECK(status='draft' OR ((
 x IS NOT NULL AND parallel_shift_pp IS NOT NULL AND short_shift_pp IS NOT NULL AND long_shift_pp IS NOT NULL
 AND interpolation_method IS NOT NULL AND extrapolation_method IS NOT NULL AND nearest_method IS NOT NULL
 AND rate_convention IS NOT NULL AND floor_mode IS NOT NULL
 AND ((floor_mode='none' AND floor_params IS NULL)
 OR (floor_mode='constant' AND jsonb_typeof(floor_params->'value_pct')='number')
 OR (floor_mode='by_bucket' AND jsonb_typeof(floor_params)='object'))
 AND length(trim(interpolation_method))>0 AND length(trim(extrapolation_method))>0
 AND length(trim(nearest_method))>0 AND length(trim(rate_convention))>0) IS TRUE))
);
CREATE INDEX ix_methodology_author ON app.methodology_version(created_by_user_id);
CREATE TABLE app.scenario (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(64) NOT NULL, version_no integer NOT NULL CHECK(version_no>0), name varchar(256) NOT NULL,
 shift_type varchar(32) NOT NULL CHECK(shift_type IN
 ('base','parallel_up','parallel_down','steepener','flattener','short_up','short_down','custom_by_bucket')),
 params jsonb CHECK(params IS NULL OR jsonb_typeof(params)='object'),
 is_predefined boolean NOT NULL DEFAULT false, is_active boolean NOT NULL DEFAULT true,
 created_by varchar(128) NOT NULL, created_by_user_id bigint REFERENCES auth.user_account,
 created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(code,version_no),
 CHECK(shift_type<>'custom_by_bucket' OR params IS NOT NULL)
);
CREATE UNIQUE INDEX uq_scenario_active ON app.scenario((CASE WHEN is_active THEN code END));
CREATE INDEX ix_scenario_author ON app.scenario(created_by_user_id);
CREATE TABLE audit.audit_log (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, occurred_at timestamptz NOT NULL DEFAULT now(),
 actor varchar(128) NOT NULL, actor_user_id bigint REFERENCES auth.user_account,
 action varchar(64) NOT NULL, entity_type varchar(64) NOT NULL, entity_id bigint NOT NULL, details jsonb
);
CREATE INDEX ix_audit_log_entity ON audit.audit_log(entity_type,entity_id);
CREATE INDEX ix_audit_actor ON audit.audit_log(actor_user_id);
CREATE TABLE calc.curve_run (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 curve_id bigint NOT NULL REFERENCES market.curve, methodology_id bigint NOT NULL, bucket_set_id bigint NOT NULL,
 status varchar(16) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','running','succeeded','failed','cancelled')),
 reporting_date date NOT NULL, created_by varchar(128) NOT NULL,
 created_by_user_id bigint REFERENCES auth.user_account, created_at timestamptz NOT NULL DEFAULT now(),
 attempt integer NOT NULL DEFAULT 0 CHECK(attempt>=0), claimed_by varchar(128), heartbeat_at timestamptz,
 started_at timestamptz, finished_at timestamptz, error_message text, engine_version varchar(64),
 CHECK(finished_at IS NULL OR (started_at IS NOT NULL AND finished_at>=started_at)),
 FOREIGN KEY(methodology_id,bucket_set_id) REFERENCES app.methodology_version(id,bucket_set_id),
 UNIQUE(id,curve_id,bucket_set_id), UNIQUE(id,bucket_set_id)
);
CREATE INDEX ix_curve_run_queue ON calc.curve_run(status,created_at);
CREATE INDEX ix_curve_run_curve ON calc.curve_run(curve_id);
CREATE INDEX ix_curve_run_methodology ON calc.curve_run(methodology_id,bucket_set_id);
CREATE INDEX ix_curve_run_author ON calc.curve_run(created_by_user_id);
CREATE TABLE calc.run_scenario (
 curve_run_id bigint NOT NULL REFERENCES calc.curve_run, scenario_id bigint NOT NULL REFERENCES app.scenario,
 PRIMARY KEY(curve_run_id,scenario_id)
);
CREATE INDEX ix_run_scenario_scenario ON calc.run_scenario(scenario_id);
CREATE TABLE calc.base_curve_point (
 curve_run_id bigint NOT NULL, curve_id bigint NOT NULL, bucket_set_id bigint NOT NULL, bucket_no smallint NOT NULL,
 rate_pct numeric(18,10) NOT NULL,
 value_source varchar(16) NOT NULL CHECK(value_source IN ('known','nearest','interpolated','extrapolated')),
 exp_factor numeric(18,12) NOT NULL, one_minus_exp_factor numeric(18,12) NOT NULL, floor_pct numeric(18,10),
 PRIMARY KEY(curve_run_id,bucket_no), UNIQUE(curve_run_id,bucket_no,curve_id),
 UNIQUE(curve_run_id,bucket_set_id,bucket_no),
 CHECK(exp_factor BETWEEN 0 AND 1 AND one_minus_exp_factor BETWEEN 0 AND 1
 AND abs(exp_factor+one_minus_exp_factor-1)<=0.000000000001),
 FOREIGN KEY(curve_run_id,curve_id,bucket_set_id) REFERENCES calc.curve_run(id,curve_id,bucket_set_id),
 FOREIGN KEY(bucket_set_id,bucket_no) REFERENCES ref.time_bucket(bucket_set_id,bucket_no)
);
CREATE TABLE calc.base_point_source (
 curve_run_id bigint NOT NULL, bucket_no smallint NOT NULL, curve_id bigint NOT NULL,
 point_no smallint NOT NULL, weight numeric(18,12), PRIMARY KEY(curve_run_id,bucket_no,point_no),
 FOREIGN KEY(curve_run_id,bucket_no,curve_id) REFERENCES calc.base_curve_point(curve_run_id,bucket_no,curve_id),
 FOREIGN KEY(curve_id,point_no) REFERENCES market.curve_point(curve_id,point_no)
);
CREATE TABLE calc.stressed_curve_point (
 curve_run_id bigint NOT NULL, scenario_id bigint NOT NULL, bucket_no smallint NOT NULL,
 shift_pp numeric(18,10) NOT NULL, rate_before_floor_pct numeric(18,10) NOT NULL, rate_pct numeric(18,10) NOT NULL,
 PRIMARY KEY(curve_run_id,scenario_id,bucket_no),
 FOREIGN KEY(curve_run_id,scenario_id) REFERENCES calc.run_scenario(curve_run_id,scenario_id),
 FOREIGN KEY(curve_run_id,bucket_no) REFERENCES calc.base_curve_point(curve_run_id,bucket_no)
);
